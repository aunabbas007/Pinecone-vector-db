from pinecone import Pinecone,ServerlessSpec

from getpass import getpass

PINECONE_API_KEY = getpass("Enter your Pinecone API key: ")

pc = Pinecone(api_key=PINECONE_API_KEY)

index_name="ai-pdf-vector-db"

# Strip the API key to remove any leading/trailing whitespace
cleaned_api_key = PINECONE_API_KEY.strip()
# Re-initialize the Pinecone client with the corrected API key
pc = Pinecone(api_key=cleaned_api_key)

if not pc.has_index(index_name):
  pc.create_index(
      name=index_name,
      dimension=384,
      metric="cosine",
      spec=ServerlessSpec(
          cloud="aws",
          region="us-east-1",
      )
  )

print(pc.list_indexes())

index=pc.Index(index_name)

vectors=[]

for i,(chunk,embedding) in enumerate(zip(chunks,chunk_embeddings)):
  vectors.append({
      "id":str(i),
      "values":embedding.tolist(),
      "metadata":{"text":chunk}
  })

  print("Vectors prepared:",len(vectors))

index.upsert(vectors=vectors)

query = "What is Artificial Intelligence?"

query_embedding=embedding_model.encode([query])

results=index.query(vector=query_embedding.tolist(),top_k=3,include_metadata=True)
print(results)

for match in results["matches"]:
    print("Score:", match["score"])
    print("Text:", match["metadata"]["text"][:500])
    print("-" * 80)

queries = [
    "What is Artificial Intelligence?",
    "What is breadth first search?",
    "What is propositional logic?",
    "What are Bayesian networks?",
    "What is machine learning?"
]

for query in queries:
    query_embedding = embedding_model.encode(query)

    results = index.query(
        vector=query_embedding.tolist(),
        top_k=2,
        include_metadata=True
    )

    print("\n" + "=" * 80)
    print("QUERY:", query)
    print("=" * 80)

    for match in results["matches"]:
        print(f"\nScore: {match['score']:.4f}")
        print(match["metadata"]["text"][:500])